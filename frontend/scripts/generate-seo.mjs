import { copyFileSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const origin = "https://saint-michel-cannes.fr";
const publicPages = readdirSync(root).filter((file) => file.endsWith(".html") && file !== "admin.html");

function languageFor(file) {
  if (file === "fr.html" || file.endsWith("-fr.html")) return "fr";
  if (file === "en.html" || file.endsWith("-en.html")) return "en";
  return "ru";
}

function groupFor(file) {
  if (["index.html", "fr.html", "en.html"].includes(file)) return "home";
  return file.replace(/-(fr|en)\.html$/, "").replace(/\.html$/, "");
}

function variantsFor(file) {
  const group = groupFor(file);
  if (group === "home") return { ru: "index.html", fr: "fr.html", en: "en.html" };
  return { ru: `${group}.html`, fr: `${group}-fr.html`, en: `${group}-en.html` };
}

function pageUrl(file) {
  return file === "index.html" ? `${origin}/` : `${origin}/${file}`;
}

function readTag(html, pattern, fallback = "") {
  return html.match(pattern)?.[1]?.trim() || fallback;
}

function escapeJson(value) {
  return value.replace(/</g, "\\u003c");
}

for (const file of publicPages) {
  const path = join(root, file);
  let html = readFileSync(path, "utf8");
  const language = languageFor(file);
  const variants = variantsFor(file);
  const title = readTag(html, /<title>([^<]*)<\/title>/i, "St Michael the Archangel Church in Cannes");
  const description = readTag(html, /<meta\s+name="description"\s+content="([^"]*)"/i, title);
  const canonical = pageUrl(file);
  const image = `${origin}/assets/seo-church.jpg`;
  const locale = language === "ru" ? "ru_RU" : language === "fr" ? "fr_FR" : "en_GB";
  const schema = {
    "@context": "https://schema.org",
    "@type": "Church",
    "@id": `${origin}/#church`,
    name: language === "ru" ? "Храм Архангела Михаила в Каннах" : language === "fr" ? "Église Saint-Michel-Archange à Cannes" : "St Michael the Archangel Church in Cannes",
    url: `${origin}/`,
    image,
    description,
    address: {
      "@type": "PostalAddress",
      streetAddress: "40 boulevard Alexandre III",
      postalCode: "06400",
      addressLocality: "Cannes",
      addressRegion: "Provence-Alpes-Côte d'Azur",
      addressCountry: "FR"
    },
    geo: {
      "@type": "GeoCoordinates",
      latitude: 43.54620413,
      longitude: 7.03962988
    },
    inLanguage: ["ru", "fr", "en"]
  };
  const seo = `
    <!-- SEO: generated by scripts/generate-seo.mjs -->
    <link rel="canonical" href="${canonical}">
    <link rel="alternate" hreflang="ru" href="${pageUrl(variants.ru)}">
    <link rel="alternate" hreflang="fr" href="${pageUrl(variants.fr)}">
    <link rel="alternate" hreflang="en" href="${pageUrl(variants.en)}">
    <link rel="alternate" hreflang="x-default" href="${pageUrl(variants.ru)}">
    <meta property="og:type" content="website">
    <meta property="og:site_name" content="St Michael the Archangel Church in Cannes">
    <meta property="og:locale" content="${locale}">
    <meta property="og:title" content="${title.replaceAll('"', "&quot;")}">
    <meta property="og:description" content="${description.replaceAll('"', "&quot;")}">
    <meta property="og:url" content="${canonical}">
    <meta property="og:image" content="${image}">
    <meta property="og:image:alt" content="St Michael the Archangel Church in Cannes">
    <meta name="twitter:card" content="summary_large_image">
    <meta name="twitter:title" content="${title.replaceAll('"', "&quot;")}">
    <meta name="twitter:description" content="${description.replaceAll('"', "&quot;")}">
    <meta name="twitter:image" content="${image}">
    <script type="application/ld+json">${escapeJson(JSON.stringify(schema))}</script>
    <!-- /SEO -->`;

  html = html.replace(/\s*<!-- SEO: generated by scripts\/generate-seo\.mjs -->[\s\S]*?<!-- \/SEO -->/g, "");
  html = html.replace(/\s*<\/head>/i, `${seo}\n  </head>`);
  writeFileSync(path, html, "utf8");
}

const sitemapPages = publicPages.filter((file) => !file.startsWith("news-detail"));
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${sitemapPages.map((file) => {
  const variants = variantsFor(file);
  return `  <url>
    <loc>${pageUrl(file)}</loc>
    <lastmod>${new Date().toISOString().slice(0, 10)}</lastmod>
    <xhtml:link rel="alternate" hreflang="ru" href="${pageUrl(variants.ru)}" />
    <xhtml:link rel="alternate" hreflang="fr" href="${pageUrl(variants.fr)}" />
    <xhtml:link rel="alternate" hreflang="en" href="${pageUrl(variants.en)}" />
    <xhtml:link rel="alternate" hreflang="x-default" href="${pageUrl(variants.ru)}" />
  </url>`;
}).join("\n")}
</urlset>
`;
writeFileSync(join(root, "public", "sitemap.xml"), sitemap, "utf8");
writeFileSync(join(root, "public", "robots.txt"), `User-agent: *\nAllow: /\nDisallow: /admin\nDisallow: /admin.html\n\nSitemap: ${origin}/sitemap.xml\n`, "utf8");
copyFileSync(join(root, "assets", "church-cross.jpg"), join(root, "public", "assets", "seo-church.jpg"));

